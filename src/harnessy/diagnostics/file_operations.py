"""Content-free, comparable receipts for file tools and human inspection.

Hashes identify observed bytes, not intent or authorship. A receipt is one
point-in-time observation; it does not promise a file cannot change afterwards.
"""
from __future__ import annotations

import hashlib
import os
import re
import stat
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


_ROOT_KINDS = {
    'base_files', 'imported_copy', 'historical_branch', 'timeline_rewind',
    'files_subdirectory', 'isolated_copy', 'unknown',
}
_OPERATIONS = {
    'read_file', 'write_file', 'replace_in_file', 'get_workspace_state',
    'inspect_file', 'file_fingerprint', 'get_file_fingerprint', 'copy_file', 'move_file', 'delete_file',
    'publish_output', 'restore_file', 'attach_file', 'run_command', 'search_text', 'other',
}
_VERIFICATION_STATUSES = {
    'HOST_ONLY_VERIFIED', 'MAPPING_NOT_VERIFIED', 'VERIFICATION_FAILED',
    'FILE_VIEW_MISMATCH', 'VERIFIED_IDENTICAL', 'HOST_ONLY',
    'VERIFIED_SAME_STORAGE', 'VERIFIED_SYNCHRONIZED_PROJECT', 'PROBE_FAILED', 'MISMATCH', 'NOT_CHECKED', 'HOST_SNAPSHOT',
}


def _digest(value: str) -> str:
    return hashlib.sha256(value.encode('utf-8', errors='surrogatepass')).hexdigest()


def _machine_id(value: Any) -> str | None:
    if value is None or value == '':
        return None
    text = str(value)
    # Provider call IDs are sometimes prefixed (call_...). Never retain paths
    # or arbitrary prose if a caller accidentally passes one as an identity.
    if len(text) <= 160 and re.fullmatch(r'[A-Za-z0-9_.:-]+', text):
        return text
    return _digest(text)


def _environment_identity(environment_id: str | None, environment_name: str | None) -> dict[str, Any]:
    identity = environment_id if isinstance(environment_id, str) and re.fullmatch(r'[0-9a-f]{32}', environment_id) else None
    # Names are display content. They are useful in model/UI receipts and local
    # logs, but the privacy exporter retains only the opaque environment ID.
    name = ''.join(character for character in environment_name if ord(character) >= 32)[:160].strip() if isinstance(environment_name, str) else ''
    return {'environment_id': identity, 'environment_name': name or None}


def file_path_identity(
    path: Path, *, workspace_id: str, working_root: Path,
    working_root_id: str = '', working_root_kind: str = '',
    environment_id: str | None = None, environment_name: str | None = None,
) -> dict[str, Any]:
    """Identify logical and resolved paths without returning either plaintext.

    ``path_id`` includes the selected-root identity, so identical relative names
    in different working copies do not compare equal. ``resolved_path_id`` can
    additionally reveal that different views reach the same physical path (for
    example, shared output-folder overlays). IDs survive process restarts.
    """
    root = Path(working_root).resolve()
    lexical = Path(os.path.abspath(path if Path(path).is_absolute() else root / path))
    resolved = lexical.resolve()
    root_id = str(working_root_id or _digest(f'harnessyxo-root-v1\0{workspace_id}\0{root}')[:24])
    # A working-root ID is generated by HarnessyXO, not a path or display name.
    if not re.fullmatch(r'[0-9a-fA-F]{24,64}', root_id):
        root_id = _digest(root_id)[:24]
    try:
        relative = lexical.relative_to(root).as_posix()
    except ValueError:
        relative = str(lexical)
    return {
        'workspace_id': _machine_id(workspace_id),
        **_environment_identity(environment_id, environment_name),
        'working_root_id': root_id.lower(),
        'working_root_kind': working_root_kind if working_root_kind in _ROOT_KINDS else 'unknown',
        'path_id': _digest(f'harnessyxo-file-path-v1\0{workspace_id}\0{root_id}\0{relative}'),
        'resolved_path_id': _digest(f'harnessyxo-resolved-file-v1\0{workspace_id}\0{resolved}'),
    }


def _stat_identity(value: os.stat_result) -> tuple[int, ...]:
    return (value.st_dev, value.st_ino, value.st_mode, value.st_size, value.st_mtime_ns, value.st_ctime_ns)


def inspect_file_fingerprint(
    path: Path, *, workspace_id: str, working_root: Path,
    working_root_id: str = '', working_root_kind: str = '',
    environment_id: str | None = None, environment_name: str | None = None,
) -> dict[str, Any]:
    """Hash a regular file off-thread with bounded memory and stability checks.

    No text is decoded or returned. A changed/replaced/unlinked file raises
    OSError rather than yielding a purportedly stable receipt. Callers must run
    this in their I/O worker, not on the UI event loop.
    """
    identity = file_path_identity(
        path, workspace_id=workspace_id, working_root=working_root,
        working_root_id=working_root_id, working_root_kind=working_root_kind,
        environment_id=environment_id, environment_name=environment_name,
    )
    source = Path(path) if Path(path).is_absolute() else Path(working_root) / path
    # O_NONBLOCK prevents accidental hangs if a path has become a FIFO/device.
    descriptor = os.open(source, os.O_RDONLY | getattr(os, 'O_NONBLOCK', 0))
    before = os.fstat(descriptor)
    if not stat.S_ISREG(before.st_mode):
        os.close(descriptor)
        raise OSError('File fingerprint requires a regular file')
    with os.fdopen(descriptor, 'rb') as handle:
        digest = hashlib.sha256()
        count = 0
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
            count += len(chunk)
        after = os.fstat(handle.fileno())
        current = source.stat()
    final_identity = file_path_identity(
        path, workspace_id=workspace_id, working_root=working_root,
        working_root_id=working_root_id, working_root_kind=working_root_kind,
        environment_id=environment_id, environment_name=environment_name,
    )
    if _stat_identity(before) != _stat_identity(after) or _stat_identity(after) != _stat_identity(current) or count != after.st_size or identity != final_identity:
        raise OSError('File changed while HarnessyXO was hashing it; refresh to obtain a stable fingerprint')
    return {
        **identity,
        'scope': 'whole_file',
        'algorithm': 'sha256',
        'sha256': digest.hexdigest(),
        'bytes': count,
        'mtime_ns': after.st_mtime_ns,
        'observed_at': datetime.now(timezone.utc).isoformat(timespec='milliseconds'),
        'stable': True,
    }


def _normalize_file_state(value: dict[str, Any] | None) -> dict[str, Any] | None:
    if not isinstance(value, dict):
        return None
    result: dict[str, Any] = {}
    digest = str(value.get('sha256') or '')
    if re.fullmatch(r'[0-9a-fA-F]{64}', digest) and value.get('scope', 'whole_file') == 'whole_file' and value.get('algorithm', 'sha256') == 'sha256':
        result.update(scope='whole_file', algorithm='sha256', sha256=digest.lower())
    for field in ('bytes', 'mtime_ns'):
        item = value.get(field)
        if isinstance(item, int) and not isinstance(item, bool) and item >= 0:
            result[field] = item
    observed_at = value.get('observed_at')
    if isinstance(observed_at, str):
        try:
            result['observed_at'] = datetime.fromisoformat(observed_at).isoformat(timespec='milliseconds')
        except ValueError:
            pass
    for field in ('exists', 'stable'):
        if isinstance(value.get(field), bool):
            result[field] = value[field]
    return result or None


def log_file_operation(
    operation: str, *, path: Path, workspace_id: str, working_root: Path,
    working_root_id: str = '', working_root_kind: str = '',
    environment_id: str | None = None, environment_name: str | None = None,
    chat_id: str | None = None, run_id: str | None = None,
    call_id: str | None = None, operation_id: str | None = None,
    before: dict[str, Any] | None = None, after: dict[str, Any] | None = None,
    file_state: dict[str, Any] | None = None, verification: dict[str, Any] | None = None,
    write_applied: bool | None = None, ok: bool | None = None,
    error_code: str | None = None, source: str = 'tool',
) -> dict[str, Any]:
    """Emit a strict, content-free receipt; return it for caller correlation.

    Existing whole-file receipt dictionaries may be passed directly. Only the
    documented scalar metadata is retained: never content, paths or free-form
    errors from tool results. ``None`` means unknown/unobserved, not absent.
    """
    from .logging import log_event

    identity = file_path_identity(
        path, workspace_id=workspace_id, working_root=working_root,
        working_root_id=working_root_id, working_root_kind=working_root_kind,
        environment_id=environment_id, environment_name=environment_name,
    )
    receipt = {
        'receipt_version': 1,
        **identity,
        'operation': operation if operation in _OPERATIONS else 'other',
        'source': source if source in {'tool', 'ui'} else 'tool',
        'operation_id': _machine_id(operation_id) or uuid.uuid4().hex,
        'chat_id': _machine_id(chat_id),
        'run_id': _machine_id(run_id),
        'call_id': _machine_id(call_id),
        'observed_at': datetime.now(timezone.utc).isoformat(timespec='milliseconds'),
        'before': _normalize_file_state(before),
        'after': _normalize_file_state(after),
        'file_state': _normalize_file_state(file_state),
        'write_applied': write_applied if isinstance(write_applied, bool) else None,
        'ok': ok if isinstance(ok, bool) else None,
        'error_code': error_code if isinstance(error_code, str) and re.fullmatch(r'[A-Z][A-Z0-9_]{0,95}', error_code) else None,
        'verification': None,
    }
    if isinstance(verification, dict):
        evidence: dict[str, Any] = {}
        for key in ('status', 'mapping_status'):
            value = verification.get(key)
            evidence[key] = value if isinstance(value, str) and value in _VERIFICATION_STATUSES else 'NOT_CHECKED'
        for key in ('mapping_verified', 'digest_match', 'vm_verified', 'ok'):
            evidence[key] = verification.get(key) if isinstance(verification.get(key), bool) else None
        for key in ('host_file_state', 'vm_file_state'):
            evidence[key] = _normalize_file_state(verification.get(key))
        receipt['verification'] = evidence
    log_event('tools', 'file_operation_receipt', **receipt)
    return receipt
